#!/usr/bin/env python3
"""Turn GitHub issues labelled `track` into tracked exams.

From the Jobs page, "Remind" opens a prefilled issue whose body contains a ```json
block in the exam shape. This job appends such exams to public/data/exams.json (so
email / Telegram / WhatsApp reminders cover them), then closes the issue.
Usage: python intake.py [--dry-run]
"""
from __future__ import annotations

import json
import re
import sys

import requests

from common import env, load_json, save_json

API = "https://api.github.com"


def headers(token: str):
    return {"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"}


def main(argv: list[str]) -> int:
    dry = "--dry-run" in argv
    token, repo = env("GITHUB_TOKEN"), env("GITHUB_REPOSITORY")
    if not token or not repo:
        print("intake: no token/repo, skipped")
        return 0
    r = requests.get(f"{API}/repos/{repo}/issues", headers=headers(token), params={"state": "open", "labels": "track", "per_page": 50}, timeout=30)
    if not r.ok:
        print("intake: list failed", r.status_code)
        return 0
    issues = [i for i in r.json() if "pull_request" not in i]
    if not issues:
        print("intake: nothing to do")
        return 0
    data = load_json("exams.json", {"exams": []})
    ids = {e["id"] for e in data["exams"]}
    added = 0
    for issue in issues:
        m = re.search(r"```json\s*(\{.*?\})\s*```", issue.get("body") or "", re.S)
        if not m:
            continue
        try:
            exam = json.loads(m.group(1))
        except json.JSONDecodeError:
            continue
        if not exam.get("id") or not exam.get("short") or not exam.get("org"):
            continue
        exam.pop("custom", None)
        msg = ""
        if exam["id"] in ids:
            # update status / dates if the user changed their mind
            for e in data["exams"]:
                if e["id"] == exam["id"]:
                    e["status"] = exam.get("status", e["status"])
                    e["application"] = {**e.get("application", {}), **exam.get("application", {})}
            msg = f"Updated `{exam['id']}` in exams.json."
        else:
            data["exams"].append(exam)
            ids.add(exam["id"])
            added += 1
            msg = f"Added `{exam['id']}` to exams.json — reminders will cover it from the next run."
        print(f"#{issue['number']}: {msg}")
        if not dry:
            requests.post(f"{API}/repos/{repo}/issues/{issue['number']}/comments", headers=headers(token), json={"body": msg + "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"}, timeout=30)
            requests.patch(f"{API}/repos/{repo}/issues/{issue['number']}", headers=headers(token), json={"state": "closed", "state_reason": "completed"}, timeout=30)
    if added and not dry:
        save_json("exams.json", data)
    print(f"intake: {added} added")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
